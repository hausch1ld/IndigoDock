export function translate(text: string, lang: Language): string {
 if(lang !== "de") return text;
 if(german[text]) return german[text];
 const trimmed = text.trim(); if(german[trimmed]) return text.replace(trimmed, german[trimmed]);
 for(const [pattern, replacement] of Object.entries(german)) {
 if(!pattern.includes("{")) continue;
 const names: string[] = []; const pieces = pattern.split(/(\{\w+\})/g);
 const expression = pieces.map(p => { if(/^\{\w+\}$/.test(p)){names.push(p);return "(.+?)";} return p.replace(/[.*+?^${}()|[\]\\]/g,"\\$&"); }).join("");
 const match = new RegExp("^"+expression+"$").exec(text);
 if(match) {let result=replacement; names.forEach((name,i)=>result=result.replaceAll(name,match[i+1]));return result;}
 }
 return text;
}
export function t(text: string) { return translate(text, language); }
